    private void filterSalesTransactions() {
        String startDate = startDateField.getText().trim();
        String endDate = endDateField.getText().trim();
        String invoiceNo = invoiceNumberField.getText().trim();
        String cashier = cmbCashier.getSelectedItem() != null
                ? cmbCashier.getSelectedItem().toString()
                : "All";

        if (!startDate.isEmpty() && !isValidDate(startDate)) {
            JOptionPane.showMessageDialog(this,
                    "Start Date must be in YYYY-MM-DD format.",
                    "Invalid Date",
                    JOptionPane.WARNING_MESSAGE);
            startDateField.requestFocus();
            return;
        }

        if (!endDate.isEmpty() && !isValidDate(endDate)) {
            JOptionPane.showMessageDialog(this,
                    "End Date must be in YYYY-MM-DD format.",
                    "Invalid Date",
                    JOptionPane.WARNING_MESSAGE);
            endDateField.requestFocus();
            return;
        }

        if ((!startDate.isEmpty() && endDate.isEmpty()) || (startDate.isEmpty() && !endDate.isEmpty())) {
            JOptionPane.showMessageDialog(this,
                    "Please provide both Start Date and End Date.",
                    "Incomplete Date Range",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!startDate.isEmpty() && !endDate.isEmpty() && startDate.compareTo(endDate) > 0) {
            JOptionPane.showMessageDialog(this,
                    "Start Date must not be later than End Date.",
                    "Invalid Date Range",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        loadSalesTransactions(startDate, endDate, invoiceNo, cashier);
    }

    private void loadSalesTransactions(String startDate, String endDate, String invoiceNo, String cashier) {
        DefaultTableModel model = (DefaultTableModel) salesTransactionTbl.getModel();
        model.setRowCount(0);

        double totalSales = 0.0;
        double totalProfit = 0.0;
        int totalItemsSold = 0;
        int totalTransactions = 0;

        StringBuilder sql = new StringBuilder();
        sql.append("SELECT ");
        sql.append("s.sale_id, ");
        sql.append("s.sale_date, ");
        sql.append("u.username AS cashier, ");
        sql.append("s.total_amount, ");
        sql.append("SUM(si.total_price - (p.cost_price * si.quantity)) AS profit, ");
        sql.append("SUM(si.quantity) AS items_sold ");
        sql.append("FROM sales s ");
        sql.append("JOIN users u ON s.user_id = u.user_id ");
        sql.append("JOIN sale_items si ON s.sale_id = si.sale_id ");
        sql.append("JOIN products p ON si.product_id = p.product_id ");
        sql.append("WHERE 1=1 ");

        boolean hasInvoiceFilter = invoiceNo != null && !invoiceNo.isEmpty();
        boolean hasDateFilter = startDate != null && !startDate.isEmpty()
                && endDate != null && !endDate.isEmpty();
        boolean hasCashierFilter = cashier != null && !cashier.equalsIgnoreCase("All");

        if (hasInvoiceFilter) {
            sql.append("AND CAST(s.sale_id AS CHAR) LIKE ? ");
        }

        if (hasDateFilter) {
            sql.append("AND DATE(s.sale_date) BETWEEN ? AND ? ");
        }

        if (hasCashierFilter) {
            sql.append("AND u.username = ? ");
        }

        sql.append("GROUP BY s.sale_id, s.sale_date, u.username, s.total_amount ");
        sql.append("ORDER BY s.sale_date DESC");

        try (Connection con = DbConnection.DatabaseConnection.dbConnection(); PreparedStatement pst = con.prepareStatement(sql.toString())) {

            int paramIndex = 1;

            if (hasInvoiceFilter) {
                pst.setString(paramIndex++, "%" + invoiceNo + "%");
            }

            if (hasDateFilter) {
                pst.setString(paramIndex++, startDate);
                pst.setString(paramIndex++, endDate);
            }

            if (hasCashierFilter) {
                pst.setString(paramIndex++, cashier);
            }

            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    double rowTotalSale = rs.getDouble("total_amount");
                    double rowProfit = rs.getDouble("profit");
                    int rowItemsSold = rs.getInt("items_sold");

                    model.addRow(new Object[]{
                        rs.getInt("sale_id"),
                        rs.getTimestamp("sale_date"),
                        rs.getString("cashier"),
                        formatCurrency(rowTotalSale),
                        formatCurrency(rowProfit),
                        rowItemsSold,
                        "Completed"
                    });

                    totalSales += rowTotalSale;
                    totalProfit += rowProfit;
                    totalItemsSold += rowItemsSold;
                    totalTransactions++;
                }
            }

            updateSummaryCards(totalSales, totalProfit, totalItemsSold, totalTransactions);

           

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error loading sales transactions: " + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadCashiers() {
        cmbCashier.removeAllItems();
        cmbCashier.addItem("All");

        String sql = "SELECT username FROM users WHERE role = 'Cashier' ORDER BY username ASC";

        try (Connection con = DbConnection.DatabaseConnection.dbConnection(); PreparedStatement pst = con.prepareStatement(sql); ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                cmbCashier.addItem(rs.getString("username"));
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error loading cashiers: " + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

