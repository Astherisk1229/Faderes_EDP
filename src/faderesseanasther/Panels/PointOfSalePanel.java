    private boolean saveSaleAndUpdateStock() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return false;
        }

        String insertSaleSql = "INSERT INTO sales (invoice_no, user_id, total_amount, payment_method, cash_tendered, changeAmount) "
                + "VALUES (?, ?, ?, ?, ?, ?)";
        String insertSaleItemSql = "INSERT INTO sale_items (sale_id, product_id, quantity, unit_price, discount, total_price) "
                + "VALUES (?, ?, ?, ?, ?, ?)";
        String updateStockSql = "UPDATE products SET stock_quantity = stock_quantity - ? "
                + "WHERE product_id = ? AND stock_quantity >= ?";

        Connection con = null;

        try {
            con = DatabaseConnection.dbConnection();
            con.setAutoCommit(false);

            int saleId;

            try (PreparedStatement salePst = con.prepareStatement(insertSaleSql, java.sql.Statement.RETURN_GENERATED_KEYS)) {
                salePst.setString(1, currentInvoiceNo);
                salePst.setInt(2, userId);
                salePst.setDouble(3, currentTotal);
                salePst.setString(4, selectedPaymentMethod);
                salePst.setDouble(5, currentCashTendered);
                salePst.setDouble(6, currentChange);

                salePst.executeUpdate();

                try (ResultSet rs = salePst.getGeneratedKeys()) {
                    if (!rs.next()) {
                        throw new SQLException("Failed to get generated sale_id.");
                    }
                    saleId = rs.getInt(1);
                }
            }

            insertSalePayment(con, saleId);

            try (PreparedStatement itemPst = con.prepareStatement(insertSaleItemSql); PreparedStatement stockPst = con.prepareStatement(updateStockSql)) {

                for (int i = 0; i < model.getRowCount(); i++) {
                    int productId = Integer.parseInt(model.getValueAt(i, 0).toString());
                    String productName = model.getValueAt(i, 1).toString();
                    int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
                    double unitPrice = Double.parseDouble(model.getValueAt(i, 5).toString());
                    double discount = Double.parseDouble(model.getValueAt(i, 6).toString());
                    double totalPrice = Double.parseDouble(model.getValueAt(i, 7).toString());

                    itemPst.setInt(1, saleId);
                    itemPst.setInt(2, productId);
                    itemPst.setInt(3, qty);
                    itemPst.setDouble(4, unitPrice);
                    itemPst.setDouble(5, discount);
                    itemPst.setDouble(6, totalPrice);
                    itemPst.executeUpdate();

                    stockPst.setInt(1, qty);
                    stockPst.setInt(2, productId);
                    stockPst.setInt(3, qty);

                    int affected = stockPst.executeUpdate();
                    if (affected == 0) {
                        throw new SQLException("Insufficient stock for product: " + productName);
                    }
                }
            }

            con.commit();

            logAuditTrail(
                    "COMPLETE_SALE",
                    "Invoice No: " + currentInvoiceNo
                    + " | Payment Method: " + selectedPaymentMethod
                    + " | Total Amount: " + moneyFormat.format(currentTotal)
                    + " | Cash Tendered: " + moneyFormat.format(currentCashTendered)
                    + " | Change: " + moneyFormat.format(currentChange)
                    + " | Discount Type: " + (selectedDiscountType == null || selectedDiscountType.isBlank() ? "NONE" : selectedDiscountType)
                    + " | Discount Customer ID: " + discountCustomerId
            );

            return true;

        } catch (SQLException ex) {
            ex.printStackTrace();

            if (con != null) {
                try {
                    con.rollback();
                } catch (SQLException rollbackEx) {
                    rollbackEx.printStackTrace();
                }
            }

            JOptionPane.showMessageDialog(this, "Failed to save sale: " + ex.getMessage());
            return false;

        } finally {
            if (con != null) {
                try {
                    con.setAutoCommit(true);
                    con.close();
                } catch (SQLException ex) {
                    ex.printStackTrace();
                }
            }
        }
    }

    private void handlePayAction() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return;
        }

        String[] paymentOptions = {"Cash", "GCash", "Card"};

        int choice = JOptionPane.showOptionDialog(
                this,
                "Select payment method:",
                "Payment Method",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                paymentOptions,
                paymentOptions[0]
        );

        if (choice == -1) {
            return;
        }

        switch (choice) {
            case 0:
                selectedPaymentMethod = "Cash";
                processCashPayment();
                break;
            case 1:
                selectedPaymentMethod = "GCash";
                processNonCashPayment("GCash");
                break;
            case 2:
                selectedPaymentMethod = "Card";
                processNonCashPayment("Card");
                break;
            default:
                break;
        }
    }

    private void processCashPayment() {
        String input = JOptionPane.showInputDialog(
                this,
                "Enter cash amount:",
                "Cash Payment",
                JOptionPane.PLAIN_MESSAGE
        );

        if (input == null) {
            return;
        }

        input = input.trim();

        if (input.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Cash amount is required.");
            return;
        }

        try {
            double cash = Double.parseDouble(input);

            if (cash < currentTotal) {
                JOptionPane.showMessageDialog(this, "Insufficient cash amount.");
                return;
            }

            currentCashTendered = cash;
            currentChange = cash - currentTotal;

            cashTetheredField.setText(moneyFormat.format(currentCashTendered));
            changeAmount1.setText(moneyFormat.format(currentChange));

            if (saveSaleAndUpdateStock()) {
                JOptionPane.showMessageDialog(this, "Cash payment accepted.");
                printReceipt();
                clearTransaction();
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Invalid cash amount.");
        }
    }

