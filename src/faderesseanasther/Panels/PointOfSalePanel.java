    private void computeCartTotals() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        double subtotal = 0.0;
        double discount = 0.0;

        for (int i = 0; i < model.getRowCount(); i++) {
            subtotal += Double.parseDouble(model.getValueAt(i, 7).toString());
            discount += Double.parseDouble(model.getValueAt(i, 6).toString());
        }

        double vat = subtotal * 0.12;
        double total = subtotal + vat;

        currentSubtotal = subtotal;
        currentVat = vat;
        currentDiscount = discount;
        currentTotal = total;

        subtotalLblAmount1.setText(moneyFormat.format(currentSubtotal));
        vatAmount1.setText(moneyFormat.format(currentVat));
        discountAmount1.setText(moneyFormat.format(currentDiscount));
        totalAmount1.setText(moneyFormat.format(currentTotal));
        cashTetheredField.setText(moneyFormat.format(currentCashTendered));
        changeAmount1.setText(moneyFormat.format(currentChange));
    }

    private void applyDiscountToCart(String discountType) {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return;
        }

        clearExistingDiscountsOnly();

        for (int i = 0; i < model.getRowCount(); i++) {
            int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
            double price = Double.parseDouble(model.getValueAt(i, 5).toString());

            double lineTotal = qty * price;

            // School project logic:
            // Apply 20% discount to the line total.
            // VAT exemption is not separately recomputed per item here;
            // this keeps the implementation simple and consistent with your current POS.
            double discountAmount = lineTotal * 0.20;
            double subtotalAfterDiscount = lineTotal - discountAmount;

            model.setValueAt(discountAmount, i, 6);
            model.setValueAt(subtotalAfterDiscount, i, 7);
        }

        computeCartTotals();

        logAuditTrail(
                "APPLY_" + discountType + "_DISCOUNT",
                "Applied " + discountType + " discount"
                + " | Customer ID: " + discountCustomerId
                + " | Customer Name: " + discountCustomerName
                + " | ID Number: " + discountIdNumber
        );
    }

