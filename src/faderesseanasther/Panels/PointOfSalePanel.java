    private void computeCashChange() {
        if (!"Cash".equalsIgnoreCase(selectedPaymentMethod)) {
            return;
        }

        String text = cashTetheredField.getText().trim();

        if (text.isEmpty()) {
            currentCashTendered = 0.0;
            currentChange = 0.0;
            changeAmount1.setText("0.00");
            return;
        }

        try {
            double cash = Double.parseDouble(text);
            currentCashTendered = cash;
            currentChange = cash - currentTotal;

            if (currentChange < 0) {
                changeAmount1.setText("Insufficient");
            } else {
                changeAmount1.setText(moneyFormat.format(currentChange));
            }
        } catch (NumberFormatException ex) {
            changeAmount1.setText("Invalid");
        }
    }

    private void handleCompletePayment() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return;
        }

        if (selectedPaymentMethod == null || selectedPaymentMethod.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a payment method.");
            return;
        }

        if ("Cash".equalsIgnoreCase(selectedPaymentMethod)) {
            validateAndCompleteCashPayment();
            return;
        }

        if ("GCash".equalsIgnoreCase(selectedPaymentMethod)) {
            if (!gcashPaymentApproved) {
                JOptionPane.showMessageDialog(this, "Please complete and confirm the GCash payment first.");
                return;
            }

            if (gcashReferenceNo.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "GCash reference number is required.");
                return;
            }

            currentCashTendered = currentTotal;
            currentChange = 0.0;

            if (saveSaleAndUpdateStock()) {
                JOptionPane.showMessageDialog(this, "GCash payment accepted.");
                printReceipt();
                clearTransaction();
            }
            return;
        }

        if ("Card".equalsIgnoreCase(selectedPaymentMethod)) {
            if (!cardPaymentApproved) {
                JOptionPane.showMessageDialog(this, "Please complete and confirm the card payment first.");
                return;
            }

            if (cardApprovalNo.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Card approval number is required.");
                return;
            }

            currentCashTendered = currentTotal;
            currentChange = 0.0;

            if (saveSaleAndUpdateStock()) {
                JOptionPane.showMessageDialog(this, "Card payment accepted.");
                printReceipt();
                clearTransaction();
            }
            return;
        }

        JOptionPane.showMessageDialog(this, "Unsupported payment method.");
    }

