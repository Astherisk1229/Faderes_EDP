    public void increaseRowQuantity(int row) {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        int productId = Integer.parseInt(model.getValueAt(row, 0).toString());
        String productName = model.getValueAt(row, 1).toString();
        int qty = Integer.parseInt(model.getValueAt(row, 3).toString());
        double price = Double.parseDouble(model.getValueAt(row, 5).toString());

        int availableStock = getAvailableStock(productId);

        if (qty >= availableStock) {
            JOptionPane.showMessageDialog(this, "Cannot add more. Insufficient stock.");
            return;
        }

        qty++;
        double subtotal = qty * price;

        model.setValueAt(qty, row, 3);
        model.setValueAt(subtotal, row, 7);

        computeCartTotals();
        logAuditTrail("ADD_TO_CART", "Increased quantity of " + productName + " to " + qty);
    }

    public void decreaseRowQuantity(int row) {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        String productName = model.getValueAt(row, 1).toString();
        int qty = Integer.parseInt(model.getValueAt(row, 3).toString());
        double price = Double.parseDouble(model.getValueAt(row, 5).toString());

        if (qty <= 1) {
            model.removeRow(row);
            logAuditTrail("REMOVE_FROM_CART", "Removed " + productName + " from cart");
        } else {
            qty--;
            double subtotal = qty * price;

            model.setValueAt(qty, row, 3);
            model.setValueAt(subtotal, row, 7);

            logAuditTrail("UPDATE_CART", "Decreased quantity of " + productName + " to " + qty);
        }

        computeCartTotals();
    }

    public void removeRowItem(int row) {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (row < 0 || row >= model.getRowCount()) {
            return;
        }

        String productName = model.getValueAt(row, 1).toString();
        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to remove \"" + productName + "\" from the cart?",
                "Remove Item",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (confirm == JOptionPane.YES_OPTION) {
            model.removeRow(row);
            computeCartTotals();
            logAuditTrail("REMOVE_FROM_CART", "Removed " + productName + " from cart");
        }
    }

