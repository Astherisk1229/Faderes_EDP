    private void showProductImage(byte[] imageBytes) {
        if (productImageLabel == null) {
            return;
        }

        if (imageBytes == null || imageBytes.length == 0) {
            productImageLabel.setIcon(null);
            productImageLabel.setText("No Image");
            return;
        }

        try {
            ImageIcon icon = new ImageIcon(imageBytes);
            Image scaled = icon.getImage().getScaledInstance(
                    prodImagePanel.getWidth(),
                    prodImagePanel.getHeight(),
                    Image.SCALE_SMOOTH
            );

            productImageLabel.setText("");
            productImageLabel.setIcon(new ImageIcon(scaled));
        } catch (Exception ex) {
            productImageLabel.setIcon(null);
            productImageLabel.setText("Image Error");
        }
    }

    private void showProductImageFromBase64(String base64Image) {
        if (productImageLabel == null) {
            return;
        }

        if (base64Image == null || base64Image.trim().isEmpty()) {
            clearProductImage();
            return;
        }

        try {
            byte[] imageBytes = Base64.getDecoder().decode(base64Image);
            showProductImage(imageBytes);
        } catch (IllegalArgumentException ex) {
            productImageLabel.setIcon(null);
            productImageLabel.setText("Invalid Image");
        }
    }
