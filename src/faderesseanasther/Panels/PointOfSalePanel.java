    private void validateAndCompleteCashPayment() {
        String input = cashTetheredField.getText().trim();

        if (input.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter cash tendered.");
            cashTetheredField.requestFocusInWindow();
            return;
        }

        try {
            double cash = Double.parseDouble(input);

            if (cash < currentTotal) {
                JOptionPane.showMessageDialog(this, "Insufficient cash amount.");
                cashTetheredField.requestFocusInWindow();
                cashTetheredField.selectAll();
                return;
            }

            currentCashTendered = cash;
            currentChange = cash - currentTotal;

            cashTetheredField.setText(moneyFormat.format(currentCashTendered));
            changeAmount1.setText(moneyFormat.format(currentChange));

            if (saveSaleAndUpdateStock()) {
                JOptionPane.showMessageDialog(this, "Cash payment accepted.");
                printReceipt();
                clearTransaction();
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Invalid cash amount.");
            cashTetheredField.requestFocusInWindow();
            cashTetheredField.selectAll();
        }
    }

