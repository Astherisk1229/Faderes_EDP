    private void openGCashPayment() {
        if (((DefaultTableModel) cartTbl.getModel()).getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return;
        }

        if (currentTotal <= 0) {
            JOptionPane.showMessageDialog(this, "Total amount must be greater than zero.");
            return;
        }

        selectedPaymentMethod = "GCash";

        resetCardState();
        resetCashState();

        cashTetheredField.setEnabled(false);
        cashTetheredField.setText(moneyFormat.format(currentTotal));
        currentCashTendered = currentTotal;
        currentChange = 0.0;
        changeAmount1.setText(moneyFormat.format(currentChange));

        GCashPaymentDialog gps = new GCashPaymentDialog(
                getParentFrame(),
                true,
                currentTotal
        );
        gps.setLocationRelativeTo(getParentFrame());
        gps.setVisible(true);

        if (gps.isPaymentApproved()) {
            gcashReferenceNo = gps.getReferenceNo() == null ? "" : gps.getReferenceNo().trim();
            gcashSenderName = gps.getSenderName() == null ? "" : gps.getSenderName().trim();
            gcashSenderMobile = gps.getSenderMobileNo() == null ? "" : gps.getSenderMobileNo().trim();

            if (gcashReferenceNo.isEmpty() || gcashSenderName.isEmpty() || gcashSenderMobile.isEmpty()) {
                resetGCashState();
                JOptionPane.showMessageDialog(this, "Incomplete GCash payment details.");
                return;
            }

            gcashPaymentApproved = true;
            JOptionPane.showMessageDialog(this, "GCash payment details confirmed.");
        } else {
            resetGCashState();
            JOptionPane.showMessageDialog(this, "GCash payment was cancelled or not approved.");
        }
    }

