    private void loginBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtnActionPerformed
        String userName = usernameField.getText().trim();
        String passWord = new String(passwordField.getPassword());

        if (userName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username.");
            usernameField.requestFocus();
            return;
        }

        if (passWord.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password.");
            passwordField.requestFocus();
            return;
        }

        String sql = "SELECT user_id, first_name, middle_name, last_name, username, password, role, status "
                + "FROM users WHERE username = ?";

        try (Connection con = DatabaseConnection.dbConnection(); PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, userName);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    int userId = rs.getInt("user_id");
                    String hashedPassword = rs.getString("password");
                    String firstName = rs.getString("first_name");
                    String middleName = rs.getString("middle_name");
                    String lastName = rs.getString("last_name");
                    String role = rs.getString("role");
                    String status = rs.getString("status");

                    String fullName = buildFullName(firstName, middleName, lastName);

                    if (!PasswordHasher.checkPassword(passWord, hashedPassword)) {
                        JOptionPane.showMessageDialog(this, "Invalid username or password.");
                        passwordField.setText("");
                        passwordField.requestFocus();
                        return;
                    }

                    if (status == null || status.trim().equalsIgnoreCase("Inactive")) {
                        JOptionPane.showMessageDialog(this, "Your account is inactive. Please contact the administrator.");
                        passwordField.setText("");
                        usernameField.requestFocus();
                        return;
                    }

                    JOptionPane.showMessageDialog(this, "Login Successful!");
                    MainFrame mainFrame = new MainFrame(userId, fullName, role);
                    mainFrame.setVisible(true);
                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(this, "Invalid username or password.");
                    passwordField.setText("");
                    usernameField.requestFocus();
                }
            }

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error connecting to database.");
        }
    }//GEN-LAST:event_loginBtnActionPerformed

    private void hideUnhideBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_hideUnhideBtnMouseClicked
        if (!passwordVisible) {
            // Unhide password
            passwordField.setEchoChar((char) 0);
            hideUnhideBtn.setIcon(new javax.swing.ImageIcon(getClass().getResource("/faderesseanasther/Icons/witness.png")));
            passwordVisible = true;
        } else {
            // Hide password again
            passwordField.setEchoChar(defaultEchoChar);
            hideUnhideBtn.setIcon(new javax.swing.ImageIcon(getClass().getResource("/faderesseanasther/Icons/hide.png")));
            passwordVisible = false;
        }
    }//GEN-LAST:event_hideUnhideBtnMouseClicked

    private String buildFullName(String firstName, String middleName, String lastName) {
        StringBuilder fullName = new StringBuilder();

        if (firstName != null && !firstName.trim().isEmpty()) {
            fullName.append(firstName.trim());
        }

        if (middleName != null && !middleName.trim().isEmpty()) {
            if (fullName.length() > 0) {
                fullName.append(" ");
            }
            fullName.append(middleName.trim());
        }

        if (lastName != null && !lastName.trim().isEmpty()) {
            if (fullName.length() > 0) {
                fullName.append(" ");
            }
            fullName.append(lastName.trim());
        }

        return fullName.length() > 0 ? fullName.toString() : "Unknown User";
    }

