    private void loadProductsToTable() {
        Connection con = DatabaseConnection.dbConnection();
        DefaultTableModel dtm = (DefaultTableModel) productTbl.getModel();
        dtm.setRowCount(0);

        String sql = "SELECT product_id, barcode, name, category_id, supplier_id, cost_price, selling_price "
                + "stock_quantity, reorder_level, product_image, created_at, updated_at "
                + "FROM products ORDER BY name ASC";

        try (PreparedStatement pst = con.prepareStatement(sql); ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                int stockQty = rs.getInt("stock_quantity");
                int reorderLevel = rs.getInt("reorder_level");

                // compute status
                String statusText = computeStockStatus(stockQty, reorderLevel);

                Object obj[] = {
                    rs.getString("product_id"),
                    rs.getString("barcode"),
                    rs.getString("name"),
                    rs.getInt("category_id"),
                    rs.getString("supplier_id"),
                    rs.getDouble("cost_price"),
                    rs.getDouble("selling_price"),
                    rs.getInt("stock_quantity"),
                    statusText,
                    rs.getInt("reorder_level"),
                    rs.getString("product_image"),
                    
                    rs.getTimestamp("created_at"),
                    rs.getTimestamp("updated_at")
                };
                dtm.addRow(obj);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Load error: " + ex.getMessage());
        }
    }
    
    
    private void browseAndEncodeImage() {
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Select Product Image");
        chooser.setFileFilter(new FileNameExtensionFilter("Images", "jpg", "jpeg", "png", "gif"));

        int result = chooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File file = chooser.getSelectedFile();

            try {
                byte[] fileBytes = Files.readAllBytes(file.toPath());
                productImageBase64 = Base64.getEncoder().encodeToString(fileBytes);

                // show filename only (not base64)
                productImageField.setText(file.getName());

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Failed to read image: " + e.getMessage());
            }
        }
    }
    
    
    private String computeStockStatus(int stockQty, int reorderLevel) {
        if (stockQty <= 0) {
            return "Out of Stock";
        }
        if (stockQty <= reorderLevel) {
            return "Low Stock";
        }
        return "In Stock";
    }
    
    private int getSupplierIdByName(Connection con, String supplierName) throws SQLException {
        String sql = "SELECT supplier_id FROM suppliers WHERE name = ? LIMIT 1";
        try (PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setString(1, supplierName);
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    return rs.getInt("supplier_id");
                }
            }
        }
        return 0;
    }


