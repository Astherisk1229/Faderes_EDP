    private void addProductBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_addProductBtnMouseClicked
           Connection con = DatabaseConnection.dbConnection();

    // --- Get values ---
    String barcode = barcodeField.getText().trim();
    String productName = productNameField.getText().trim();

    Object catObj = cmbProdCategory.getSelectedItem();
    Object supObj = cmbSupplierName.getSelectedItem();

    String costStr = costPriceField.getText().trim();
    String sellStr = sellingPriceField.getText().trim();
    String qtyStr  = quantityStockField.getText().trim();
    String reStr   = reorderLevelField.getText().trim();

    // --- Validate required fields ---
    if (barcode.isEmpty() || productName.isEmpty() || catObj == null || supObj == null
            || costStr.isEmpty() || sellStr.isEmpty() || qtyStr.isEmpty() || reStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all required fields.");
        return;
    }

    // Barcodes should be String, but you can enforce digits-only if you want
    if (!barcode.matches("\\d+")) {
        JOptionPane.showMessageDialog(this, "Barcode must contain digits only.");
        return;
    }

    int categoryId = ((ComboItem) catObj).getId();
    int supplierId = ((ComboItem) supObj).getId();

    double costPrice, sellingPrice;
    int stockQty, reorderLevel;

    try {
        costPrice = Double.parseDouble(costStr);
        sellingPrice = Double.parseDouble(sellStr);
        stockQty = Integer.parseInt(qtyStr);
        reorderLevel = Integer.parseInt(reStr);
    } catch (NumberFormatException nfe) {
        JOptionPane.showMessageDialog(this, "Cost/Selling must be numbers and Stock/Reorder must be integers.");
        return;
    }

    if (costPrice < 0 || sellingPrice < 0 || stockQty < 0 || reorderLevel < 0) {
        JOptionPane.showMessageDialog(this, "Values cannot be negative.");
        return;
    }

    // --- Prevent duplicate barcode (code-level check) ---
    try (PreparedStatement check = con.prepareStatement(
            "SELECT 1 FROM products WHERE barcode = ? LIMIT 1")) {
        check.setString(1, barcode);
        try (ResultSet rs = check.executeQuery()) {
            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Barcode already exists. Please use another barcode.");
                return;
            }
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Duplicate check error: " + ex.getMessage());
        return;
    }

    // --- Insert to products table ---
    String sql = "INSERT INTO products "
            + "(barcode, name, category_id, supplier_id, cost_price, selling_price, stock_quantity, reorder_level, product_image, created_at, updated_at) "
            + "VALUES (?,?,?,?,?,?,?,?,?,?,?)";

    try (PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, barcode);
        pst.setString(2, productName);
        pst.setInt(3, categoryId);
        pst.setInt(4, supplierId);
        pst.setDouble(5, costPrice);
        pst.setDouble(6, sellingPrice);
        pst.setInt(7, stockQty);
        pst.setInt(8, reorderLevel);

        // store Base64 (or NULL if none)
        if (productImageBase64 == null || productImageBase64.isEmpty()) {
            pst.setNull(9, java.sql.Types.LONGVARCHAR);
        } else {
            pst.setString(9, productImageBase64);
        }

        Timestamp now = new Timestamp(System.currentTimeMillis());
        pst.setTimestamp(10, now);
        pst.setTimestamp(11, now);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Product added successfully!");
        clearFields();
        loadProductsToTable();

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Add product error: " + ex.getMessage());
    }
    }//GEN-LAST:event_addProductBtnMouseClicked

