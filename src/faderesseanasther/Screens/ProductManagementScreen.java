private boolean hasChanges() {
    String newBarcode = barcodeField.getText().trim();
    String newName = productNameField.getText().trim();
    String newCost = costPriceField.getText().trim();
    String newSell = sellingPriceField.getText().trim();
    String newQty = quantityStockField.getText().trim();
    String newReorder = reorderLevelField.getText().trim();

    Object catObj = cmbProdCategory.getSelectedItem();
    Object supObj = cmbSupplierName.getSelectedItem();
    int newCatId = (catObj instanceof ComboItem) ? ((ComboItem) catObj).getId() : -1;
    int newSupId = (supObj instanceof ComboItem) ? ((ComboItem) supObj).getId() : -1;

    return !newBarcode.equals(origBarcode)
            || !newName.equals(origName)
            || !newCost.equals(origCost)
            || !newSell.equals(origSell)
            || !newQty.equals(origQty)
            || !newReorder.equals(origReorder)
            || newCatId != origCatId
            || newSupId != origSupId;
}

private void resetToOriginal() {
    barcodeField.setText(origBarcode);
    productNameField.setText(origName);
    costPriceField.setText(origCost);
    sellingPriceField.setText(origSell);
    quantityStockField.setText(origQty);
    reorderLevelField.setText(origReorder);

    selectComboById(cmbProdCategory, origCatId);
    selectComboById(cmbSupplierName, origSupId);

    // Optional: message
    label.setText("Changes reverted to original values.");
}

private void selectComboById(javax.swing.JComboBox<ComboItem> combo, int id) {
    if (combo == null || combo.getItemCount() == 0) return;

    for (int i = 0; i < combo.getItemCount(); i++) {
        ComboItem item = combo.getItemAt(i);
        if (item != null && item.getId() == id) {
            combo.setSelectedIndex(i);
            return;
        }
    }

    // If not found, optional: select first item
    combo.setSelectedIndex(0);
}
