    private void setupTableRowClick() {
        stockTbl.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                if (!editMode) {
                    JOptionPane.showMessageDialog(null, "Click Edit first before selecting a row.");
                    stockTbl.clearSelection();
                    return;
                }
                int row = stockTbl.getSelectedRow();
                if (row == -1) {
                    return;
                }
                loadSelectedTransactionToForm(row);
            }
        });
    }
    private void updateProductStock(Connection con, int productId, int qtyChange) throws SQLException {
        PreparedStatement pst = con.prepareStatement(
                "UPDATE products SET stock_quantity = stock_quantity + ? WHERE product_id = ?"
        );
        pst.setInt(1, qtyChange);
        pst.setInt(2, productId);
        pst.executeUpdate();
        pst.close();
    }
    private void loadSelectedTransactionToForm(int row) {
        try {
            DefaultTableModel model = (DefaultTableModel) stockTbl.getModel();

            selectedTransactionId = Integer.parseInt(model.getValueAt(row, 0).toString());
            int productId = Integer.parseInt(model.getValueAt(row, 1).toString());
            String transactionType = model.getValueAt(row, 2).toString().trim();
            int quantity = Integer.parseInt(model.getValueAt(row, 3).toString());
            String referenceNumber = model.getValueAt(row, 4).toString();
            java.sql.Date transactionDate = java.sql.Date.valueOf(model.getValueAt(row, 5).toString());
            String reason = model.getValueAt(row, 6) == null ? "" : model.getValueAt(row, 6).toString();

            originalProductId = productId;
            originalQuantity = quantity;
            originalTransactionType = transactionType;
            rowLoaded = true;

            String comboText = findProductComboText(productId);

            if (transactionType.equalsIgnoreCase("Stock In")) {
                clearStockOutFields();
                jTabbedPane1.setSelectedComponent(stockInPanel);

                productStockInCmb.setSelectedItem(comboText);
                quantityStockInField.setText(String.valueOf(quantity));
                referenceNumberStockInField.setText(referenceNumber);
                jDateChooser3.setDate(transactionDate);
                jTextArea5.setText(reason);

            } else if (transactionType.equalsIgnoreCase("Stock Out")) {
                clearStockInFields();
                jTabbedPane1.setSelectedComponent(stockOutPanel);

                productStockOutCmb.setSelectedItem(comboText);
                quantityStockOutField.setText(String.valueOf(quantity));
                referenceNumberStockOutField.setText(referenceNumber);
                dateStockOutField.setDate(transactionDate);
                remarksStockOutField.setText(reason);
            }

            stockLbl.setText("Loaded: " + transactionType + " | Transaction ID: " + selectedTransactionId);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading selected row: " + e.getMessage());
        }
    }

    private String findProductComboText(int productId) {
        for (int i = 0; i < productStockInCmb.getItemCount(); i++) {
            String item = productStockInCmb.getItemAt(i);
            if (item.startsWith(productId + " - ")) {
                return item;
            }
        }
        return null;
    }

