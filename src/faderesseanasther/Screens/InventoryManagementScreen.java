    private void loadProducts() {
        Connection con = DatabaseConnection.dbConnection();

        try {
            PreparedStatement pst = con.prepareStatement(
                    "SELECT product_id, name FROM products ORDER BY name"
            );
            ResultSet rs = pst.executeQuery();

            productStockInCmb.removeAllItems();
            productStockOutCmb.removeAllItems();

            while (rs.next()) {
                int id = rs.getInt("product_id");
                String name = rs.getString("name");

                String item = id + " - " + name;
                productStockInCmb.addItem(item);
                productStockOutCmb.addItem(item);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading products: " + e.getMessage());
        }
    }

    private int getSelectedProductId(javax.swing.JComboBox<String> comboBox) {
        String selected = comboBox.getSelectedItem() == null ? "" : comboBox.getSelectedItem().toString();

        if (selected.isEmpty() || !selected.contains(" - ")) {
            return -1;
        }

        return Integer.parseInt(selected.split(" - ")[0].trim());
    }

