    private void addStockOutBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_addStockOutBtnMouseClicked
        try {
            int productId = getSelectedProductId(productStockOutCmb);
            String qtyText = quantityStockOutField.getText().trim();
            String refNo = referenceNumberStockOutField.getText().trim();
            String remarks = remarksStockOutField.getText().trim();
            java.util.Date utilDate = dateStockOutField.getDate();

            if (productId == -1 || qtyText.isEmpty() || utilDate == null) {
                JOptionPane.showMessageDialog(this, "Please fill in all required stock out fields.");
                return;
            }

            int qty = Integer.parseInt(qtyText);
            if (qty <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity must be greater than 0.");
                return;
            }

            int currentStock = getCurrentStock(productId);
            if (qty > currentStock) {
                JOptionPane.showMessageDialog(this, "Insufficient stock.");
                return;
            }

            java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

            Connection con = DatabaseConnection.dbConnection();

            String insertSql = "INSERT INTO inventory_transactions "
                    + "(product_id, transaction_type, quantity, reference_number, transaction_date, reason) "
                    + "VALUES (?, ?, ?, ?, ?, ?)";

            PreparedStatement pst = con.prepareStatement(insertSql);
            pst.setInt(1, productId);
            pst.setString(2, "Stock Out");
            pst.setInt(3, qty);
            pst.setString(4, refNo);
            pst.setDate(5, sqlDate);
            pst.setString(6, remarks);
            pst.executeUpdate();

            updateProductStock(productId, -qty);

            JOptionPane.showMessageDialog(this, "Stock Out transaction added successfully.");
            loadInventoryTransactions();
            clearStockOutFields();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantity must be a valid number.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error adding stock out: " + e.getMessage());
        }
    }//GEN-LAST:event_addStockOutBtnMouseClicked

