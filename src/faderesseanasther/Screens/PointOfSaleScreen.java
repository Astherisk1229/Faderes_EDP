    private void addProductToCartByBarcode() {
        String barcode = barcodeField.getText().trim();

        if (barcode.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a barcode.");
            return;
        }

        Connection con = DatabaseConnection.dbConnection();

        try {
            String sql = "SELECT product_id, name, selling_price, stock_quantity FROM products WHERE barcode = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, barcode);
            ResultSet rs = pst.executeQuery();

            if (!rs.next()) {
                JOptionPane.showMessageDialog(this, "Product not found.");
                return;
            }

            int productId = rs.getInt("product_id");
            String productName = rs.getString("name");
            double price = rs.getDouble("selling_price");
            int stockQty = rs.getInt("stock_quantity");

            if (stockQty <= 0) {
                JOptionPane.showMessageDialog(this, "Insufficient stock.");
                return;
            }

            addOrUpdateCartRow(productId, productName, price, stockQty);
            barcodeField.setText("");
            computeTotals();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error adding product: " + e.getMessage());
        }
    }

    private void generateInvoiceNumber() {
        currentInvoiceNo = "INV-" + System.currentTimeMillis();
        jLabel1.setText("Invoice No: " + currentInvoiceNo);
    }

    private void addOrUpdateCartRow(int productId, String productName, double price, int availableStock) {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            String existingName = model.getValueAt(i, 0).toString();

            if (existingName.equalsIgnoreCase(productName)) {
                int currentQty = Integer.parseInt(model.getValueAt(i, 1).toString());

                if (currentQty + 1 > availableStock) {
                    JOptionPane.showMessageDialog(this, "Insufficient stock.");
                    return;
                }

                int newQty = currentQty + 1;
                double discount = Double.parseDouble(model.getValueAt(i, 3).toString());
                double subtotal = (newQty * price) - discount;

                model.setValueAt(newQty, i, 1);
                model.setValueAt(subtotal, i, 4);
                return;
            }
        }

        model.addRow(new Object[]{
            productName,
            1,
            price,
            0.00,
            price
        });
    }

    private void setupCartTableHeader() {
        DefaultTableCellRenderer headerRenderer = new DefaultTableCellRenderer();
        headerRenderer.setFont(new Font("Segoe UI", Font.BOLD, 13));
        headerRenderer.setBackground(new Color(239, 198, 46));

        for (int i = 0; i < cartTbl.getColumnCount(); i++) {
            cartTbl.getColumnModel().getColumn(i).setHeaderRenderer(headerRenderer);
        }
    }

    private void startDateTimeTimer() {
        if (dateTimeTimer != null && dateTimeTimer.isRunning()) {
            return;
        }

        dateTimeTimer = new Timer(1000, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
                jLabel2.setText("Date: " + sdf.format(new Date()));
            }
        });
        dateTimeTimer.start();
    }

    private void computeTotals() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        currentSubtotal = 0.0;
        currentDiscount = 0.0;

        for (int i = 0; i < model.getRowCount(); i++) {
            double price = Double.parseDouble(model.getValueAt(i, 2).toString());
            int qty = Integer.parseInt(model.getValueAt(i, 1).toString());
            double discount = Double.parseDouble(model.getValueAt(i, 3).toString());

            currentSubtotal += (price * qty);
            currentDiscount += discount;
        }

        currentVat = 0.0;
        currentTotal = currentSubtotal + currentVat - currentDiscount;

        subtotalLbl.setText("Subtotal: " + String.format("%.2f", currentSubtotal));
        vatLbl.setText("VAT (Optional): " + String.format("%.2f", currentVat));
        discountLbl.setText("Discount: " + String.format("%.2f", currentDiscount));
        totalAmountLbl.setText("Total Amount: " + String.format("%.2f", currentTotal));
        cashTetheredLbl.setText("Cash Tendered: 0.00");
        changeLbl.setText("Change: 0.00");

        label.setText("Ready: Product added to cart.");
    }

    private void clearCartTable() {
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();
        model.setRowCount(0);
    }

