    public void loadUsers(){
        DefaultTableModel model = (DefaultTableModel) UserListTbl.getModel();
        model.setRowCount(0);
        
        String sql = "Select id, role, full_name, username, status, created_at FROM users";
        
        try (Connection con = DBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery()){
            
            while (rs.next()){
                int id = rs.getInt("id");
                String role = rs.getString("role");
                String fullName = rs.getString("full_name");
                String username = rs.getString("username");
                String status = rs.getString("status");
                Timestamp createdAt = rs.getTimestamp("created_at");
                
                model.addRow(new Object[] {id, role, fullName, username, status, createdAt});
            }
        }catch (Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(this,"Failed to load users: " + e.getMessage());
        }
                
    }
    
    
    
    
    
