    private void registerBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_registerBtnMouseClicked
      Connection con = DatabaseConnection.dbConnection();
      
      String fname = firstName.getText();
      String lname = lastName.getText();
      String role = cmbRole.getSelectedItem().toString();
      String email = emAil.getText();
      String cNumber = contactNumber.getText();
      String uName = userName.getText();
      String password = passwordField.getText();
      String confirmPassword = confirmPasswordField.getText();
      String status = cmbStatus.getSelectedItem().toString();
      
      try {
          PreparedStatement pst = con.prepareStatement("INSERT into users(first_name, last_name, role, email, contact_number, username, password, status)" + "VALUES(?, ?, ?, ?, ?, ?, ?, ?)");
          
          pst.setString(1, fname);
          pst.setString(2, lname);
          pst.setString(3, role);
          pst.setString(4, email);
          pst.setString(5, cNumber);
          pst.setString(6, uName);
          pst.setString(7, password);
          pst.setString(8, status);
          pst.executeUpdate();
          JOptionPane.showMessageDialog(null, "Data added successfully!");
          
     
      }catch(SQLException ex){
          System.out.println(ex);
      }
    }//GEN-LAST:event_registerBtnMouseClicked

